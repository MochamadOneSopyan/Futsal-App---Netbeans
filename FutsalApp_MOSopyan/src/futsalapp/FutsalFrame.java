    private void buttonSimpanActionPerformed(java.awt.event.ActionEvent evt) {                                             
        // TODO add your handling code here:
        // 1. Ambil data dari form
        String namaLapangan = textNama.getText().trim();
    String tipeLapangan = (String) comboTipe.getSelectedItem();
    String hargaStr = textHarga.getText().trim();
        String status = (String) comboStatus.getSelectedItem();
        
        // 2. Validasi input kosong
    if (namaLapangan.isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Nama Lapangan tidak boleh kosong!",
            "Peringatan",
            JOptionPane.WARNING_MESSAGE);
        textNama.requestFocus();
        return;
    }
    
    if (hargaStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Harga per jam tidak boleh kosong!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            textHarga.requestFocus();
            return;
        }
    
    // 3. Validasi angka untuk harga
    int hargaPerJam;
        try {
            hargaPerJam = Integer.parseInt(hargaStr);
            if (hargaPerJam <= 0) {
                JOptionPane.showMessageDialog(this, "Harga per jam harus lebih besar dari 0!", "Peringatan", JOptionPane.WARNING_MESSAGE);
                textHarga.requestFocus();
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Harga per jam harus berupa angka yang valid!", "Error", JOptionPane.ERROR_MESSAGE);
            textHarga.requestFocus();
            return;
        }
    
    
    // 4. Proses Simpan ke Database
    try {
            Connection koneksi = Koneksi.getKoneksi();
            if (koneksi == null) {
                JOptionPane.showMessageDialog(this, "Koneksi database gagal!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            String query = "INSERT INTO lapangan (nama_lapangan, tipe_lapangan, harga_per_jam, status) VALUES (?, ?, ?, ?)";
            PreparedStatement ps = koneksi.prepareStatement(query);
            ps.setString(1, namaLapangan);
            ps.setString(2, tipeLapangan);
            ps.setInt(3, hargaPerJam);
            ps.setString(4, status);
            
            int hasil = ps.executeUpdate();
            if (hasil > 0) {
                JOptionPane.showMessageDialog(this, "Data lapangan berhasil disimpan!", "Sukses", JOptionPane.INFORMATION_MESSAGE);
                
                // Reset form setelah berhasil simpan
                textNama.setText("");
                textHarga.setText("");
                comboTipe.setSelectedIndex(0);
                comboStatus.setSelectedIndex(0);
                textNama.requestFocus();
            }
            ps.close();
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error database: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    

    }                                            

