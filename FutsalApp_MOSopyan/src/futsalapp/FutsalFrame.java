    private void buttonEditActionPerformed(java.awt.event.ActionEvent evt) {                                           
        // TODO add your handling code here:
    // Ambil data dari form
    String id = textId.getText().trim();
    String namaLapangan = textNama.getText().trim();
    String tipeLapangan = (String) comboTipe.getSelectedItem();
    String hargaStr = textHarga.getText().trim();
    String status = (String) comboStatus.getSelectedItem();

    // Validasi ID
    if (id.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Masukkan ID data yang ingin diedit!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Validasi nama
    if (namaLapangan.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Nama Lapangan tidak boleh kosong!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE);
        textNama.requestFocus();
        return;
    }

    // Validasi harga
    if (hargaStr.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Harga per jam tidak boleh kosong!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE);
        textHarga.requestFocus();
        return;
    }

    int hargaPerJam;

    try {
        hargaPerJam = Integer.parseInt(hargaStr);

        if (hargaPerJam <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Harga per jam harus lebih besar dari 0!",
                    "Peringatan",
                    JOptionPane.WARNING_MESSAGE);
            textHarga.requestFocus();
            return;
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Harga harus berupa angka!",
                "Error",
                JOptionPane.ERROR_MESSAGE);
        textHarga.requestFocus();
        return;
    }

    // Konfirmasi edit
    int konfirmasi = JOptionPane.showConfirmDialog(
            this,
            "Apakah Anda yakin ingin mengubah data ini?",
            "Konfirmasi Edit",
            JOptionPane.YES_NO_OPTION
    );

    if (konfirmasi != JOptionPane.YES_OPTION) {
        return;
    }

    // Update database
    try {

        Connection koneksi = Koneksi.getKoneksi();

        if (koneksi == null) {
            JOptionPane.showMessageDialog(this,
                    "Koneksi database gagal!",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        String query = "UPDATE lapangan SET "
                + "nama_lapangan = ?, "
                + "tipe_lapangan = ?, "
                + "harga_per_jam = ?, "
                + "status = ? "
                + "WHERE id = ?";

        PreparedStatement ps = koneksi.prepareStatement(query);

        ps.setString(1, namaLapangan);
        ps.setString(2, tipeLapangan);
        ps.setInt(3, hargaPerJam);
        ps.setString(4, status);
        ps.setInt(5, Integer.parseInt(id));

        int hasil = ps.executeUpdate();

        if (hasil > 0) {

            JOptionPane.showMessageDialog(this,
                    "Data berhasil diubah!",
                    "Sukses",
                    JOptionPane.INFORMATION_MESSAGE);

            // Reset form
            textId.setText("");
            textNama.setText("");
            textHarga.setText("");
            comboTipe.setSelectedIndex(0);
            comboStatus.setSelectedIndex(0);
            textNama.requestFocus();

        } else {

            JOptionPane.showMessageDialog(this,
                    "Data dengan ID tersebut tidak ditemukan!",
                    "Peringatan",
                    JOptionPane.WARNING_MESSAGE);
        }

        ps.close();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error database: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "ID harus berupa angka!",
                "Error",
                JOptionPane.ERROR_MESSAGE);
    }
    }                                          

