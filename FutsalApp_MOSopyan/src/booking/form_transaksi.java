    public void tampilData() {
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
    model.addColumn("ID Booking");
    model.addColumn("Nama Lapangan");
    model.addColumn("Nama Penyewa");
    model.addColumn("No HP");
    model.addColumn("Tanggal Booking");
    model.addColumn("Total Harga");
    model.addColumn("Jenis Pembayaran");
    model.addColumn("Status Pembayaran");
    model.addColumn("Jumlah Bayar");     // <-- Kolom Baru
    model.addColumn("Sisa Pembayaran");  // <-- Kolom Baru
    model.addColumn("Kembalian"); // <-- Kolom Baru


    try {
        java.sql.Connection conn = futsalapp.Koneksi.getKoneksi();
        String sql = "SELECT * FROM booking";
        java.sql.Statement stm = conn.createStatement();
        java.sql.ResultSet rs = stm.executeQuery(sql);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id_booking"),
                rs.getString("nama_lapangan"),
                rs.getString("nama_penyewa"),
                rs.getString("no_hp"),
                rs.getDate("tanggal_booking"),
                rs.getInt("total_harga"),
                rs.getString("jenis_pembayaran"),
                rs.getString("status_pembayaran"),
                rs.getInt("jumlah_bayar"),     // <-- Ambil dari DB
                rs.getInt("sisa_pembayaran"),   // <-- Ambil dari DB
                rs.getInt("kembalian") // <-- Ambil dari database
            });
        }
        
        // Masukkan model ke JTable Anda (pastikan nama variabel JTable Anda sesuai, misal jTable1)
        jTable1.setModel(model); // Sesuaikan dengan nama variabel JTable Anda
        
        rs.close();
        stm.close();
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal memuat data transaksi: " + e.getMessage());
    }
}
    
    
