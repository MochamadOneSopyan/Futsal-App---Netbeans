    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {                                         
        // TODO add your handling code here:
        // 1. Cek apakah baris pada tabel sudah dipilih
    int baris = jTable1.getSelectedRow();
    
    if (baris == -1) {
        javax.swing.JOptionPane.showMessageDialog(
            this, 
            "Silakan pilih data transaksi yang ingin dihapus pada tabel!", 
            ", Peringatan", 
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }
    
    // 2. Konfirmasi penghapusan data kepada pengguna
    int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(
        this, 
        "Apakah Anda yakin ingin membatalkan (cancel) booking ini?", 
        "Konfirmasi Pembatalan", 
        javax.swing.JOptionPane.YES_NO_OPTION
    );
    
    if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
        try {
            // Ambil id_booking dan nama_lapangan dari baris yang dipilih
            String idBooking = jTable1.getValueAt(baris, 0).toString();
            String namaLapangan = jTable1.getValueAt(baris, 1).toString();
            
            java.sql.Connection conn = futsalapp.Koneksi.getKoneksi();
            
            // 3. Hapus data dari tabel booking berdasarkan id_booking
            String sqlHapus = "DELETE FROM booking WHERE id_booking = ?";
            java.sql.PreparedStatement pstHapus = conn.prepareStatement(sqlHapus);
            pstHapus.setString(1, idBooking);
            pstHapus.executeUpdate();
            pstHapus.close();
            
            // 4. Update kembali status lapangan di tabel lapangan menjadi "Tersedia"
            String sqlUpdate = "UPDATE lapangan SET status = 'Tersedia' WHERE nama_lapangan = ?";
            java.sql.PreparedStatement pstUpdate = conn.prepareStatement(sqlUpdate);
            pstUpdate.setString(1, namaLapangan);
            pstUpdate.executeUpdate();
            pstUpdate.close();
            
            javax.swing.JOptionPane.showMessageDialog(
                this, 
                "Booking berhasil dibatalkan dan status lapangan kembali Tersedia!"
            );
            
            // 5. Refresh tampilan tabel secara otomatis
            tampilData();
            
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(
                this, 
                "Gagal menghapus data: " + e.getMessage(), 
                "Error", 
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }
    }                                        

